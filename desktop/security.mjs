export function sameOrigin(url, origin) {
  try {
    const parsed = new URL(url);
    return parsed.origin === origin && parsed.protocol === 'http:' && !parsed.username && !parsed.password;
  } catch { return false; }
}

export function permittedRequest(url, origin, resourceType) {
  if (sameOrigin(url, origin)) return true;
  // Image attachments are generated locally. No remote frame, worker or script may load.
  return (resourceType === 'image' && (url.startsWith('data:image/') || url.startsWith(`blob:${origin}/`))) || (resourceType === 'other' && url.startsWith(`blob:${origin}/`));
}

export function permittedExternalURL(value) {
  try {
    const url = new URL(value);
    if (url.protocol !== 'https:' || url.username || url.password || url.port || url.search || url.hash || /%(?:2f|5c|2e)/i.test(url.pathname) || value.includes('\\')) return null;
    const repository = '/solomongs/Ollam-manager';
    if (url.hostname === 'github.com' && (url.pathname === repository || url.pathname.startsWith(`${repository}/releases`) || url.pathname.startsWith(`${repository}/archive/`))) {
      if (url.pathname === `${repository}/releases` || url.pathname.startsWith(`${repository}/releases/`) || url.pathname === repository || url.pathname.startsWith(`${repository}/archive/`)) return url.href;
    }
    if (url.hostname === 'ollama.com' && (url.pathname === '/library' || url.pathname.startsWith('/library/') || url.pathname === '/download' || url.pathname.startsWith('/download/'))) return url.href;
    return null;
  } catch { return null; }
}

export function configureWindow(window, origin, openExternal = () => {}) {
  const contents = window.webContents;
  contents.setWindowOpenHandler(({url}) => {
    const external = permittedExternalURL(url);
    if (external) Promise.resolve(openExternal(external)).catch(() => {});
    return {action:'deny'};
  });
  contents.on('will-navigate', (event, url) => { if (!sameOrigin(url, origin)) event.preventDefault(); });
  contents.on('will-redirect', (event, url) => { if (!sameOrigin(url, origin)) event.preventDefault(); });
  contents.on('will-attach-webview', event => event.preventDefault());
}

export function configureSession(session, origin) {
  session.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
  session.setPermissionCheckHandler(() => false);
  session.on('will-download', (event, item) => {
    const urls = item.getURLChain();
    // Allow workspace exports generated by the local UI; never fetch a remote download.
    if (!urls.length || urls.some(url => !sameOrigin(url, origin) && !url.startsWith(`blob:${origin}/`))) event.preventDefault();
  });
  session.webRequest.onBeforeRequest((details, callback) => {
    callback({cancel:!permittedRequest(details.url, origin, details.resourceType)});
  });
}

export function parseSmokeArguments(argv) {
  const enabled = argv.includes('--desktop-smoke-test');
  const options = {};
  for (const [flag, key] of [['--smoke-output=', 'output'], ['--smoke-user-data=', 'userData']]) {
    const values = argv.filter(value => value.startsWith(flag));
    if (values.length > 1) throw new Error(`Specify ${flag.slice(0,-1)} once.`);
    if (values.length) {
      if (!enabled) throw new Error(`${flag.slice(0,-1)} requires --desktop-smoke-test.`);
      const value = values[0].slice(flag.length);
      if (!value || !path.isAbsolute(value)) throw new Error(`${flag.slice(0,-1)} requires an absolute path.`);
      options[key] = path.normalize(value);
    }
  }
  if (enabled && (!options.output || !options.userData)) throw new Error('Smoke mode requires --smoke-output and --smoke-user-data absolute paths.');
  return {enabled, ...options};
}
